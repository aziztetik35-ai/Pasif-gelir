export const STRINGS: Record<Lang, Dict> = { en, tr, de, es, fr, it, pt, nl };

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

const TRADE_KEYS: Record<Trade, StringKey> = {
  hvac: "tradeHvac",
  electrical: "tradeElectrical",
  elevator: "tradeElevator",
  appliance: "tradeAppliance",
  machine: "tradeMachine",
  security: "tradeSecurity",
  plumbing: "tradePlumbing",
  general: "tradeGeneral",
};

export function tradeLabel(lang: Lang, trade: Trade): string {
  return translate(lang, TRADE_KEYS[trade]);
}

/** Pick a supported language from a BCP-47 language code such as "tr" or "pt". */
export function resolveLang(code: string | null | undefined): Lang {
  const c = (code ?? "").toLowerCase().slice(0, 2);
  return (LANGS as string[]).includes(c) ? (c as Lang) : "en";
}
